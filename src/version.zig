        return switch (level) {
            .l0 => .{ .a = self.a + 1 },
            .l1 => .{ .a = self.a, .b = self.b + 1, .c = self.c, .d = self.d },
            .l2 => .{ .a = self.a, .b = self.b, .c = self.c + 1, .d = self.d },
            .l3 => .{ .a = self.a, .b = self.b, .c = self.c, .d = self.d + 1 },
        };
    }

    /// Р В РЎС›Р В Р’ВµР В РЎвЂќР РЋР С“Р РЋРІР‚С™ Р В Р вЂ Р В Р’ВµР РЋР вЂљР РЋР С“Р В РЎвЂР В РЎвЂ Р В Р вЂ  Р В РЎвЂ”Р В Р’ВµР РЋР вЂљР В Р’ВµР В РўвЂР В Р’В°Р В Р вЂ¦Р В Р вЂ¦Р РЋРІР‚в„–Р В РІвЂћвЂ“ Р В Р’В±Р РЋРЎвЂњР РЋРІР‚С›Р В Р’ВµР РЋР вЂљ (Р В Р вЂ¦Р РЋРЎвЂњР В Р’В¶Р В Р’ВµР В Р вЂ¦ Р В РЎВР В РЎвЂР В Р вЂ¦Р В РЎвЂР В РЎВР РЋРЎвЂњР В РЎВ `max_len` Р В Р’В±Р В Р’В°Р В РІвЂћвЂ“Р РЋРІР‚С™).
    pub fn write(self: Version, buf: []u8) []const u8 {
        return std.fmt.bufPrint(buf, "{d}.{d}.{d}.{d}", .{ self.a, self.b, self.c, self.d }) catch unreachable;
    }

    pub fn eql(self: Version, other: Version) bool {
        return self.a == other.a and self.b == other.b and self.c == other.c and self.d == other.d;
    }
};

